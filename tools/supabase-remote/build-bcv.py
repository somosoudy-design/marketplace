#!/usr/bin/env python3
"""Build the exact BCV backend release for review. Never connects or deploys."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = '20261014202228'
NAME = 'bcv_effective_dates'
MIGRATION = ROOT / f'supabase/migrations/{VERSION}_{NAME}.sql'
OUT = ROOT / 'tools/supabase-remote/aplicar-bcv-ves.sql'
MANIFEST = ROOT / 'docs/BCV_VES_RELEASE.json'
BEFORE = {
    'current_rate(text)': '1b58a5d6a04120c1ab8cd55c51f1f1fb',
    'ingest_rate(text,text,numeric,timestamp with time zone,jsonb,boolean)': 'c531294e1ccac0e88b93c3b1edbd11d4',
    'pricing_snapshot_current()': 'a86cb8033453805626ffc25c297a1238',
}
AFTER = {
    'current_rate(text)': 'ec69de556081f8abe6fb974302f582e8',
    'ingest_rate(text,text,numeric,timestamp with time zone,jsonb,boolean)': 'f2e8c00fc79b715375872f97ad42ea15',
    'pricing_snapshot_current()': 'f08bb2d1ae6739ee3b4394fccf44756d',
}


def assertions(hashes):
    return '\n'.join(f"""  if md5(pg_get_functiondef('public.{sig}'::regprocedure)) is distinct from '{digest}' then
    raise exception 'Unexpected financial definition: {sig}; nothing applied.';
  end if;""" for sig, digest in hashes.items())


def build():
    source = MIGRATION.read_text().rstrip()
    assert '$bcv_source$' not in source
    sql = f"""-- GENERATED by tools/supabase-remote/build-bcv.py. Never edit manually.
-- ONLY Marketplace mimnotafmfasvwrclxan; ONLY BCV/VES backend correction.
-- Requires Oliver's review/authorization. No seed, rates, business-data updates or financial transactions.
-- Atomic + idempotent. Reject wrong project, conflicting history and financial drift.
begin;
select pg_advisory_xact_lock(hashtextextended('hayazgo:bcv-ves', 0));
do $bcv_guard$
declare v_url text;
begin
  select decrypted_secret into strict v_url from vault.decrypted_secrets where name='kora_project_url';
  if rtrim(v_url,'/') is distinct from 'https://mimnotafmfasvwrclxan.supabase.co' then
    raise exception 'Wrong project; only Marketplace is authorized.';
  end if;
  if exists (select 1 from supabase_migrations.schema_migrations
    where (version='{VERSION}' and name is distinct from '{NAME}') or (name='{NAME}' and version<>'{VERSION}')) then
    raise exception 'Conflicting BCV migration history; nothing applied.';
  end if;
  if not exists (select 1 from supabase_migrations.schema_migrations where version='{VERSION}') then
{assertions(BEFORE)}
    if to_regclass('public.bcv_banking_calendar') is not null
       or to_regprocedure('public._bcv_business_day(timestamptz)') is not null
       or to_regprocedure('public._bcv_next_business_day(timestamptz)') is not null then
      raise exception 'Unrecorded BCV objects; nothing applied.';
    end if;
  end if;
end $bcv_guard$;
do $bcv_apply$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version='{VERSION}') then
    execute $bcv_source$
{source}
$bcv_source$;
    insert into supabase_migrations.schema_migrations(version,name) values ('{VERSION}','{NAME}');
  end if;
end $bcv_apply$;
do $bcv_verify$
begin
{assertions(AFTER)}
  if (select count(*) from public.bcv_banking_calendar where day between '2026-01-01' and '2026-12-31') <> 365
     or (select count(*) from public.bcv_banking_calendar where day between '2026-01-01' and '2026-12-31'
           and extract(isodow from day)<6 and not is_business_day) <> 22 then
    raise exception 'Incomplete or unexpected 2026 banking calendar; nothing applied.';
  end if;
  if not (select relrowsecurity from pg_class where oid='public.bcv_banking_calendar'::regclass)
     or has_table_privilege('anon','public.bcv_banking_calendar','SELECT')
     or has_function_privilege('anon','public._bcv_business_day(timestamptz)','EXECUTE')
     or has_function_privilege('authenticated','public._bcv_business_day(timestamptz)','EXECUTE')
     or has_function_privilege('anon','public._bcv_next_business_day(timestamptz)','EXECUTE')
     or has_function_privilege('authenticated','public._bcv_next_business_day(timestamptz)','EXECUTE') then
    raise exception 'Unexpected BCV calendar privileges; nothing applied.';
  end if;
end $bcv_verify$;
notify pgrst, 'reload schema';
commit;
select version,name from supabase_migrations.schema_migrations where version='{VERSION}';
select public.rate_status('USD/VES');
"""
    def digest(path):
        return hashlib.sha256(path.read_bytes()).hexdigest()

    # Relative-import closure: the two existing entrypoints and only their dependencies.
    def closure(entry):
        seen = set()
        def visit(path):
            path = path.resolve()
            if path in seen:
                return
            if not path.is_relative_to(ROOT / 'supabase/functions'):
                raise ValueError(f'Import outside deploy tree: {path}')
            seen.add(path)
            for dependency in re.findall(r"(?:from\s+|import\s*)['\"](\.[^'\"]+\.ts)['\"]", path.read_text()):
                visit(path.parent / dependency)
        visit(entry)
        return {str(p.relative_to(ROOT / 'supabase/functions')): digest(p) for p in sorted(seen)}

    manifest = {
        'project_ref': 'mimnotafmfasvwrclxan', 'status': 'release_payload', 'deployment_evidence': 'docs/BCV_VES_DESPLIEGUE_2026-10-14.json',
        'migration': str(MIGRATION.relative_to(ROOT)), 'migration_sha256': digest(MIGRATION),
        'sql_bundle': str(OUT.relative_to(ROOT)), 'sql_bundle_sha256': hashlib.sha256(sql.encode()).hexdigest(),
        'preflight_financial_md5': BEFORE, 'postflight_financial_md5': AFTER,
        'edge_functions': [
            {'name': name, 'entrypoint_path': f'{name}/index.ts', 'verify_jwt': name == 'panel-api',
             'authentication': 'existing service/job-token' if name == 'rates-sync' else 'existing user JWT + admin authorization',
             'files_sha256': closure(ROOT / f'supabase/functions/{name}/index.ts')}
            for name in ['rates-sync', 'panel-api']
        ],
        'mobile_release_required': False,
        'calendar_valid_through': '2026-12-31',
        'calendar_sources': ['https://iusdata.com/wp-content/uploads/2025/11/Calendario-Bancario-2026.pdf', 'https://asobanca.com.ve/wp-content/uploads/2025/11/calendario-bancario-asobanca-6.pdf'],
        'provider_date_contract': 'https://github.com/enzonotario/dolarapi.com/blob/main/cron/ve/bcv.extractor.js',
    }
    return sql, json.dumps(manifest, indent=2, ensure_ascii=False) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sql, manifest = build()
    if args.check:
        if not OUT.exists() or OUT.read_text() != sql or not MANIFEST.exists() or MANIFEST.read_text() != manifest:
            parser.error('BCV release differs from reviewed source; regenerate and review')
        print('BCV SQL and both Edge file manifests match their exact sources')
    else:
        OUT.write_text(sql)
        MANIFEST.write_text(manifest)
        print('BCV SQL and exact Edge manifests prepared; nothing deployed')
