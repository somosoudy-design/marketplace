#!/usr/bin/env python3
"""Build only the two operational seller migrations; never connect or deploy."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'tools/supabase-remote/aplicar-mi-tienda-operativa.sql'
MIGRATIONS = (
    ('20261011172600', 'seller_product_editor'),
    ('20261011174200', 'seller_fulfillment_detail'),
)


def build():
    chunks = ["""-- Generated by tools/supabase-remote/build-mi-tienda.py. Do not edit manually.
-- ONLY Marketplace (mimnotafmfasvwrclxan), ONLY these two migrations.
-- Review/authorize remote SQL separately from EAS Update; this file never deploys itself.
-- SQL Editor: paste the entire file and Run as postgres, then inspect the final results.
-- Atomic and repeatable: recorded migrations are skipped; conflicting history aborts.
-- No seeds, accounts, business-data writes or migration-history rewrites.
begin;
select pg_advisory_xact_lock(hashtextextended('hayazgo:mi-tienda-operativa', 0));

do $seller_guard$
declare v_url text; v_signature text;
begin
  if to_regclass('vault.decrypted_secrets') is null then
    raise exception 'Missing project identity in Vault; nothing applied.';
  end if;
  select decrypted_secret into strict v_url from vault.decrypted_secrets where name = 'kora_project_url';
  if rtrim(v_url, '/') is distinct from 'https://mimnotafmfasvwrclxan.supabase.co' then
    raise exception 'Wrong project: this script is only for Marketplace; nothing applied.';
  end if;
  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception 'Missing migration history; nothing applied.';
  end if;
  foreach v_signature in array array[
    'public.is_store_member(uuid)', 'public.is_admin()', 'public.is_service_role()',
    'public.require_store_member(uuid)', 'public.set_product_costs(uuid,jsonb,jsonb)',
    'public.advance_fulfillment(uuid,text,text,text,text)', 'public._order_payment_level(uuid)'
  ] loop
    if to_regprocedure(v_signature) is null then
      raise exception 'Missing prerequisite %; nothing applied.', v_signature;
    end if;
  end loop;
  if to_regclass('public.moderation_events') is null
     or to_regclass('public.product_images') is null
     or to_regclass('public.fulfillment_events') is null then
    raise exception 'Missing seller prerequisites; nothing applied.';
  end if;
"""]
    for version, name in MIGRATIONS:
        chunks.append(f"""  if exists (
    select 1 from supabase_migrations.schema_migrations
     where (version = '{version}' and name is distinct from '{name}')
        or (name = '{name}' and version <> '{version}')
  ) then
    raise exception 'Conflicting migration history for {name}; nothing applied.';
  end if;
""")
    chunks.append('end $seller_guard$;\n')
    for version, name in MIGRATIONS:
        source = (ROOT / f'supabase/migrations/{version}_{name}.sql').read_text().rstrip()
        tag = f'$seller_sql_{version}$'
        if tag in source:
            raise ValueError('Migration contains reserved SQL delimiter')
        chunks.append(f"""
-- Original migration: {version}_{name}.sql
do $seller_apply_{version}$
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '{version}') then
    execute {tag}
{source}
{tag};
    insert into supabase_migrations.schema_migrations(version, name) values ('{version}', '{name}');
  end if;
end $seller_apply_{version}$;
""")
    chunks.append("""
do $seller_verify$
declare v_signature text; v_function regprocedure;
begin
  foreach v_signature in array array[
    'public.seller_save_product(uuid,uuid,jsonb,jsonb,jsonb,jsonb,jsonb)',
    'public.seller_editor_ready()', 'public.seller_fulfillment_detail(uuid,uuid)',
    'public.seller_orders_ready()'
  ] loop
    v_function := to_regprocedure(v_signature);
    if v_function is null then
      raise exception 'Recorded migration missing function %; nothing applied.', v_signature;
    end if;
    if has_function_privilege('anon', v_function, 'EXECUTE')
       or not has_function_privilege('authenticated', v_function, 'EXECUTE')
       or not has_function_privilege('service_role', v_function, 'EXECUTE') then
      raise exception 'Unexpected grants on %; nothing applied.', v_signature;
    end if;
  end loop;
  if (select prosecdef from pg_proc where oid = 'public.seller_save_product(uuid,uuid,jsonb,jsonb,jsonb,jsonb,jsonb)'::regprocedure)
     or not (select prosecdef from pg_proc where oid = 'public.seller_fulfillment_detail(uuid,uuid)'::regprocedure) then
    raise exception 'Unexpected security mode; nothing applied.';
  end if;
end $seller_verify$;
notify pgrst, 'reload schema';
commit;

select version, name from supabase_migrations.schema_migrations
 where version in ('20261011172600', '20261011174200') order by version;
select public.seller_editor_ready() as catalog_supported, public.seller_orders_ready() as orders_supported;
""")
    return ''.join(chunks)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if committed SQL differs from its sources')
    args = parser.parse_args()
    sql = build()
    if args.check:
        if not OUT.exists() or OUT.read_text() != sql:
            parser.error('generated seller SQL is out of date')
        print('Seller SQL matches both source migrations')
    else:
        OUT.write_text(sql)
        print(f'2 migrations -> {OUT.relative_to(ROOT)}')
