// Builds the demo catalog for a hosted Supabase project (the one the test APK uses), and the script that takes
// it out again. Unlike supabase/seed.sql it creates no users, no orders and no demo exchange rates: testers sign
// up themselves and prices are converted with the live rates. Images are Storage paths (buckets catalog and
// stores, folder demo/), the same files as supabase/seed-assets; they are uploaded to the project once
// (docs/ENTORNO.md, «Imágenes del catálogo demo»). The repository can be private: nothing is served from GitHub.
//
//   node tools/demo-assets/build-remote-catalog.mjs
//   -> supabase/remote-demo/catalogo-demo.sql        (run once; refuses to run twice)
//   -> supabase/remote-demo/quitar-catalogo-demo.sql (deletes it, or hides it if orders already use it)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brands, categories, collections, stores } from './catalog.mjs';
import { catalogSql, q } from './catalog-sql.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const outDir = join(root, 'supabase/remote-demo');

// the Storage path inside its bucket, as in the local seed (catalog/demo/…, stores/demo/…)
const asset = (_bucket, path) => path;

// payment methods (fictitious receiving details) and logistics (demo tariffs) from the local seed config;
// its demo exchange rates and the order-number prefix stay local only
function seedConfigSections(...names) {
  const text = readFileSync(join(here, 'seed-config.sql'), 'utf8');
  const sections = text.split(/^(?=-- ---------- )/m);
  return names.map((name) => {
    const found = sections.find((s) => s.startsWith(`-- ---------- ${name}`));
    if (!found) throw new Error(`seed-config.sql has no "${name}" section`);
    return found.replace(/^update public\.app_settings .*$/m, '').trimEnd() + '\n';
  }).join('\n');
}

const list = (items) => items.map(q).join(', ');
const storeSlugs = list(stores.map((s) => s.slug));
const carrierCodes = "'kora_moto', 'zoom', 'mrw', 'tealca', 'retiro'";
const zoneCodes = "'caracas', 'centro', 'occidente', 'andes', 'oriente', 'sur'";
const paymentCodes = "'pago_movil', 'transferencia_ves', 'zelle', 'usdt_trc20', 'efectivo_usd'";

const load = `-- =====================================================================
-- GENERATED by tools/demo-assets/build-remote-catalog.mjs — do not edit by hand.
-- DEMO catalog for the hosted test project: ${stores.length} stores, ${categories.length} categories, demo shipping
-- tariffs and payment methods with FICTITIOUS receiving details. Every store, product, image, carrier, rate
-- and pickup point is flagged is_demo, and the app labels them as demonstration.
-- No users, no passwords, no orders, no exchange rates (the live rates apply).
-- Images: Supabase Storage, buckets catalog and stores, folder demo/ (upload supabase/seed-assets first).
-- Remove with quitar-catalogo-demo.sql.
-- =====================================================================
begin;

do $$
begin
  if exists (select 1 from public.stores where slug in (${storeSlugs}))
     or exists (select 1 from public.carriers where code in (${carrierCodes})) then
    raise exception 'El catálogo de demostración ya está cargado en este proyecto.';
  end if;
end $$;

-- ---------- categories & brands ----------
${catalogSql({ asset })}
${seedConfigSections('payment methods', 'logistics')}
commit;
`;

const remove = `-- =====================================================================
-- GENERATED by tools/demo-assets/build-remote-catalog.mjs — do not edit by hand.
-- Takes the demo catalog out of the hosted test project (Supabase › SQL Editor › Run).
-- If an order already uses a demo product or store, nothing is deleted: the demo stores are suspended, their
-- products hidden and the demo shipping rates turned off, so order history stays intact.
-- Payment methods go back to disabled with empty instructions only while they still hold the demo details.
-- =====================================================================
begin;

update public.payment_methods set enabled = false, instructions = '{}'
 where code in (${paymentCodes}) and instructions->>'nota' ilike '%fictici%de desarrollo%';

do $$
declare
  used int;
begin
  select count(*) into used from public.order_items oi join public.products p on p.id = oi.product_id where p.is_demo;
  if used > 0 then
    update public.stores set status = 'suspended' where is_demo and slug in (${storeSlugs});
    update public.products set moderation_status = 'suspended' where is_demo;
    update public.shipping_rates set active = false where is_demo;
    raise notice 'Hay pedidos con productos de demostración (% líneas): se ocultó el catálogo sin borrarlo.', used;
    return;
  end if;

  delete from public.collections where slug in (${list(collections.map((c) => c.slug))});
  delete from public.commission_rules where note like 'Demo:%';
  delete from public.products where is_demo;
  delete from public.stores where is_demo and slug in (${storeSlugs});
  delete from public.pickup_points where is_demo;
  delete from public.shipping_rates where is_demo;
  delete from public.shipping_methods m using public.carriers c
   where m.carrier_id = c.id and c.is_demo and c.code in (${carrierCodes})
     and not exists (select 1 from public.shipping_rates r where r.method_id = m.id);
  delete from public.carriers c where c.is_demo and c.code in (${carrierCodes})
     and not exists (select 1 from public.shipping_methods m where m.carrier_id = c.id);
  delete from public.shipping_zones z where z.code in (${zoneCodes})
     and not exists (select 1 from public.shipping_rates r where r.zone_id = z.id);
  delete from public.brands b where b.slug in (${list(brands.map((b) => b.slug))})
     and not exists (select 1 from public.products p where p.brand_id = b.id);
  -- subcategories first, then their parents, and only those no real product uses
  delete from public.categories c where c.slug in (${list(categories.filter((c) => c.parent).map((c) => c.slug))})
     and not exists (select 1 from public.products p where p.category_id = c.id);
  delete from public.categories c where c.slug in (${list(categories.filter((c) => !c.parent).map((c) => c.slug))})
     and not exists (select 1 from public.products p where p.category_id = c.id)
     and not exists (select 1 from public.categories k where k.parent_id = c.id);
  raise notice 'Catálogo de demostración eliminado.';
end $$;

commit;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'catalogo-demo.sql'), load);
writeFileSync(join(outDir, 'quitar-catalogo-demo.sql'), remove);
console.log(`wrote supabase/remote-demo/ (catalog ${(load.length / 1024).toFixed(0)} KB, images as Storage paths)`);
